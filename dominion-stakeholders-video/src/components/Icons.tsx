import React, {createContext, useContext, useId} from 'react';
import {C} from '../lib/theme';

/*
 * Lineal-colour icon set (Flaticon "detailed mixed / lineal color" look):
 * white rounded strokes over flat #0072CE shapes, drawn on a 512 grid.
 * Stroke width is computed so it renders at 5 CSS px = 10 px in the 4K output.
 * `progress` animates the icon: strokes draw on, fills bloom in after.
 */

type Ctx = {sw: number; dp: number; fp: number; clip: string};
const IconCtx = createContext<Ctx>({sw: 16, dp: 1, fp: 1, clip: ''});

const L: React.FC<{d: string; o?: number}> = ({d, o = 1}) => {
  const {sw, dp} = useContext(IconCtx);
  if (dp <= 0.001) return null;
  return (
    <path
      d={d}
      fill="none"
      stroke={C.white}
      strokeWidth={sw}
      strokeLinecap="round"
      strokeLinejoin="round"
      pathLength={1}
      strokeDasharray="1 1"
      strokeDashoffset={1 - dp}
      opacity={o}
    />
  );
};

const F: React.FC<{d: string; color?: string; o?: number; clip?: boolean}> = ({d, color = C.blue, o = 1, clip}) => {
  const {fp, clip: clipId} = useContext(IconCtx);
  if (fp <= 0.001) return null;
  return <path d={d} fill={color} opacity={fp * o} clipPath={clip ? `url(#${clipId})` : undefined} />;
};

const BG: React.FC<{d: string}> = ({d}) => <path d={d} fill={C.bg} />;

// ---------------------------------------------------------------- geometry
const rr = (x: number, y: number, w: number, h: number, r: number) =>
  `M${x + r} ${y} H${x + w - r} Q${x + w} ${y} ${x + w} ${y + r} V${y + h - r} Q${x + w} ${y + h} ${x + w - r} ${y + h} H${x + r} Q${x} ${y + h} ${x} ${y + h - r} V${y + r} Q${x} ${y} ${x + r} ${y} Z`;
const circ = (cx: number, cy: number, r: number) =>
  `M${cx - r} ${cy} A${r} ${r} 0 1 0 ${cx + r} ${cy} A${r} ${r} 0 1 0 ${cx - r} ${cy} Z`;
const ln = (x1: number, y1: number, x2: number, y2: number) => `M${x1} ${y1} L${x2} ${y2}`;
const gear = (cx: number, cy: number, ro: number, ri: number, teeth: number) => {
  let d = '';
  const step = (Math.PI * 2) / teeth;
  for (let i = 0; i < teeth; i++) {
    const a = i * step - Math.PI / 2;
    const pts = [
      [a - step * 0.3, ri],
      [a - step * 0.17, ro],
      [a + step * 0.17, ro],
      [a + step * 0.3, ri],
    ];
    for (const [ang, r] of pts) {
      const x = (cx + Math.cos(ang) * r).toFixed(1);
      const y = (cy + Math.sin(ang) * r).toFixed(1);
      d += (d === '' ? 'M' : 'L') + x + ' ' + y + ' ';
    }
  }
  return d + 'Z';
};
const tableGrid = (x: number, y: number, w: number, h: number) => {
  const hdr = h * 0.25;
  const rows = [y + hdr, y + hdr + (h - hdr) / 3, y + hdr + ((h - hdr) * 2) / 3];
  const cols = [x + w / 3, x + (w * 2) / 3];
  return {
    outline: rr(x, y, w, h, Math.min(28, w * 0.08)),
    header: `M${x + 24} ${y} H${x + w - 24} Q${x + w} ${y} ${x + w} ${y + 24} V${y + hdr} H${x} V${y + 24} Q${x} ${y} ${x + 24} ${y} Z`,
    lines: [
      ...rows.map((ry) => ln(x, ry, x + w, ry)),
      ...cols.map((cx) => ln(cx, y + hdr, cx, y + h)),
    ].join(' '),
    cols,
    hdr,
  };
};

