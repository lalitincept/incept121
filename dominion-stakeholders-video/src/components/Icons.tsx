export type IconName = keyof typeof ICONS;

export const Icon: React.FC<{
  name: string;
  size: number;
  progress?: number;
  strokePx?: number;
  style?: React.CSSProperties;
}> = ({name, size, progress = 1, strokePx = 5, style}) => {
  const id = useId().replace(/:/g, '');
  const Comp = ICONS[name];
  if (!Comp) throw new Error('Unknown icon ' + name);
  const sw = (strokePx * 512) / size;
  const dp = Math.min(1, Math.max(0, progress / 0.72));
  const fp = Math.min(1, Math.max(0, (progress - 0.32) / 0.6));
  return (
    <svg width={size} height={size} viewBox="0 0 512 512" style={{overflow: 'visible', display: 'block', ...style}}>
      <IconCtx.Provider value={{sw, dp, fp, clip: 'c' + id}}>
        <Comp />
      </IconCtx.Provider>
    </svg>
  );
};
