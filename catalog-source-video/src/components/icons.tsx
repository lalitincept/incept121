const P = (d: string) => <path d={d} />;
const R = (x: number, y: number, w: number, h: number, rx = 0) => <rect x={x} y={y} width={w} height={h} rx={rx} />;
const O = (cx: number, cy: number, r: number) => <circle cx={cx} cy={cy} r={r} />;
const E = (cx: number, cy: number, rx: number, ry: number) => <ellipse cx={cx} cy={cy} rx={rx} ry={ry} />;

const gearPath = (cx: number, cy: number, rOuter: number, rInner: number, teeth: number) => {
  const pts: string[] = [];
  const step = (Math.PI * 2) / teeth;
  for (let i = 0; i < teeth; i++) {
    const a = i * step - Math.PI / 2;
    const w = step * 0.22;
    const pt = (r: number, ang: number) => `${(cx + r * Math.cos(ang)).toFixed(1)} ${(cy + r * Math.sin(ang)).toFixed(1)}`;
    pts.push(`${i === 0 ? 'M' : 'L'}${pt(rInner, a - step / 2 + w)}`);
    pts.push(`L${pt(rOuter, a - w)}`);
    pts.push(`L${pt(rOuter, a + w)}`);
    pts.push(`L${pt(rInner, a + step / 2 - w)}`);
  }
  return pts.join(' ') + 'Z';
};

